"""Regenerate the checked-in U8g2 fonts. Normal firmware builds do not need this.

Windows: python scripts/generate_display_fonts.py
Other systems: python scripts/generate_display_fonts.py --converter /path/to/bdfconv
"""
import argparse
import os
import pathlib
import subprocess
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
REVISION = 'd6c8499c5f2707cac8eccd09fd8f677d12b17977'
BASE = f'https://raw.githubusercontent.com/olikraus/u8g2/{REVISION}/tools/font/'
FONTS = ['helvB24', 'helvB18', 'helvB14', 'helvB08', 'helvR08']
GLYPHS = '32-126,160-383,8211,8322'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--converter', type=pathlib.Path)
    args = parser.parse_args()
    cache = ROOT / '.pio' / 'display-fonts'
    cache.mkdir(parents=True, exist_ok=True)
    converter = args.converter
    if converter is None:
        if os.name != 'nt':
            raise SystemExit('Supply a native bdfconv using --converter /path/to/bdfconv.')
        converter = cache / 'bdfconv.exe'
        urllib.request.urlretrieve(BASE + 'bdfconv/bdfconv.exe', converter)
    output = ROOT / 'src' / 'fonts'
    output.mkdir(exist_ok=True)
    generated = ['// Generated by scripts/generate_display_fonts.py; see LICENSE.txt.',
                 '#pragma once', '#include <U8g2_for_Adafruit_GFX.h>', '']
    for name in FONTS:
        bdf = cache / (name + '.bdf')
        urllib.request.urlretrieve(BASE + 'bdf/' + name + '.bdf', bdf)
        converted = cache / (name + '.h')
        subprocess.run([str(converter), '-b', '0', '-f', '1', '-m', GLYPHS,
                        '-n', 'sen66_' + name, '-o', str(converted), str(bdf)], check=True)
        generated.append(converted.read_text())
    (output / 'DisplayFonts.h').write_text('\n'.join(generated), encoding='utf-8')
    # Preserve upstream permission and attribution verbatim.
    comments = []
    for line in bdf.read_text().splitlines():
        if line.startswith('COMMENT'):
            comments.append(line.removeprefix('COMMENT').lstrip())
    (output / 'LICENSE.txt').write_text(
        'U8g2 Adobe Helvetica BDF sources\nUpstream revision: ' + REVISION +
        '\nhttps://github.com/olikraus/u8g2/tree/' + REVISION + '/tools/font/bdf\n\n' +
        '\n'.join(comments) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
